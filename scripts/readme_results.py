"""Write the "released model" tables of README.md from release directories (scripts/release.sh).

    uv run python scripts/readme_results.py runs/final [runs/final-4m ...]            # rewrites README.md
    uv run python scripts/readme_results.py runs/final --print                        # only prints the block

Every number comes from <release>/model-card.json, RELEASE.json, bench.jsonl and parity_report.json. The
block between the two RELEASE-TABLE markers of the README is replaced; nothing else is touched.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "<!-- RELEASE-TABLE:BEGIN (generated by scripts/readme_results.py; do not edit by hand) -->"
END = "<!-- RELEASE-TABLE:END -->"
SPLITS = {"test": "held-out test", "final": "final slice (read once)"}
# (weights, mode, label): what the tables show, in this order
ROWS = [
    ("float32", "open_book_ranked", "site default: retrieved facts + ranking prior"),
    ("int8", "open_book_ranked", "site default, **int8 weights** (what the browser runs)"),
    ("float32", "open_book_retrieved", "retrieved facts only (no prior)"),
    ("float32", "open_book", "free generation, open-book"),
    ("float32", "closed_book", "free generation, closed-book (no facts in the prompt)"),
    ("float32", "first_hit", "the retriever's first fact, no language model"),
]


def pct(x) -> str:
    return "-" if x is None else f"{100 * x:.1f}"


def release_block(release: Path) -> str:
    card = json.loads((release / "model-card.json").read_text(encoding="utf-8"))
    info = json.loads((release / "RELEASE.json").read_text(encoding="utf-8"))
    evaluation = card["evaluation"]
    headline = {label: entry["headline"] for label, entry in evaluation.items() if isinstance(entry, dict)}
    model, training = card["model"], card["training"]
    lines = [f"**`{card['name']}`** ({model['params']:,} parameters; run `{info['run']}`, {info['checkpoint']} "
             f"checkpoint, released {info['released_at'][:16]}). Greedy decoding; exact match and the other "
             f"columns in %.", ""]
    lines += ["| Questions | Decoding | n | Exact match | Token F1 | Right topic | Curated sentence | Refusal P / R | "
              "Unsupported numbers |", "| --- | --- | ---: | ---: | ---: | ---: | ---: | --- | ---: |"]
    site = next(m for m in ("open_book_ranked", "open_book_retrieved", "open_book") if m in headline["float32"])
    seen = headline["float32"][site].get("seen")
    if seen:
        lines.append(f"| seen in training (sample) | site default | {seen['n']} | {pct(seen['em'])} | "
                     f"{pct(seen['f1'])} | {pct(seen['right_topic_rate'])} | {pct(seen['verbatim_rate'])} | "
                     f"{pct(seen['refusal_precision'])} / {pct(seen['refusal_recall'])} | "
                     f"{pct(seen['unsupported_number_rate'])} |")
    for split, split_name in SPLITS.items():
        for weights, mode, label in ROWS:
            m = headline.get(weights, {}).get(mode, {}).get(split)
            if not m:
                continue
            refusal = "- / 0" if mode == "first_hit" else f"{pct(m['refusal_precision'])} / {pct(m['refusal_recall'])}"
            lines.append(f"| {split_name} | {label} | {m['n']} | {pct(m['em'])} | {pct(m['f1'])} | "
                         f"{pct(m['right_topic_rate'])} | {pct(m['verbatim_rate'])} | {refusal} | "
                         f"{pct(m['unsupported_number_rate'])} |")
    lines.append("")

    # per kind of question, site default, on the strictest split available
    full = evaluation["float32"]["full"]
    mode = site
    split = "final" if "final" in full[mode] else "test"
    kinds = {"single": "one fact", "multi": "several facts", "meta": "about the model", "chitchat": "small talk",
             "oos": "out of scope"}
    by_kind = full[mode][split]["by_kind"]
    by_lang = full[mode][split]["by_lang"]
    cells = [f"{name} {pct(by_kind[k]['em'])} (n={by_kind[k]['n']})" for k, name in kinds.items() if k in by_kind]
    cells += [f"{lang} {pct(m['em'])}" for lang, m in by_lang.items()]
    lines.append(f"Site default by kind of question and language ({SPLITS[split]}, float32, exact match): "
                 + "; ".join(cells) + ".")

    test = headline["float32"][mode].get("test", {})
    if "gold_in_top1" in test:
        retrieval = training.get("retrieval") or {}
        how = (f"BM25 fused with the model's own ranking, weight {retrieval.get('weight')}" if retrieval
               else "BM25 alone")
        lines.append(f"Retriever ({how}), held-out test: gold fact first for {pct(test['gold_in_top1'])}%, in the top "
                     f"2 for {pct(test['gold_in_top2'])}%, in the top 4 for {pct(test['gold_in_top4'])}%; exact match "
                     f"{pct(test.get('em_when_gold_retrieved'))}% when it was retrieved and "
                     f"{pct(test.get('em_when_gold_missed'))}% when it was not.")
    prior = (evaluation["float32"].get("decoding") or {}).get("prior") or {}
    if prior.get("weight"):
        lines.append(f"Ranking prior: `{prior['kind']}`, weight {prior['weight']}, chosen on the validation questions.")
    init = training.get("init_from") or {}
    if init:
        lines.append(f"Started from `{init.get('dir')}`: {init.get('steps'):,} steps of next-token prediction on the "
                     f"Wikipedia slice ({init.get('tokens_seen', 0) / 1e6:.0f}M tokens seen, "
                     f"{init.get('train_seconds', 0) / 60:.0f} min, validation perplexity "
                     f"{(init.get('final_val') or {}).get('val_ppl')}), from random weights; then "
                     f"{training['steps']:,} steps on the questions ({training['train_seconds'] / 60:.0f} min).")
    else:
        lines.append(f"Trained from random weights on the questions only: {training['steps']:,} steps, "
                     f"{training['train_seconds'] / 60:.0f} min.")

    quant = card.get("quantisation") or {}
    same = {label: e.get("answers_identical_to_float32") for label, e in evaluation.items() if isinstance(e, dict)}
    if quant.get("i8"):
        lines.append(f"Quantisation: int8 relative weight error {quant['i8']['mean_relative_weight_rmse']}, largest "
                     f"logit drift {quant['i8']['max_abs_logit_drift_vs_float32']}; answers identical to float32: "
                     f"{same.get('int8')} (int8), {same.get('float16')} (float16).")
    files = card.get("files") or {}
    sizes = [f"`{name}` {files[name]['bytes']:,} bytes ({files[name]['brotli']:,} with brotli)"
             for name in ("model.i8.bin", "retrieval.json", "tokenizer.json")
             if isinstance(files.get(name), dict) and files[name].get("brotli")]
    if sizes:
        lines.append("Files the site loads: " + ", ".join(sizes) + ".")
    bench = release / "bench.jsonl"
    if bench.exists():
        runs = [json.loads(line) for line in bench.read_text(encoding="utf-8").splitlines() if line.strip()]
        speed = ", ".join(f"{r['decodeTokPerSec']:,.0f} tokens/s ({r['kernel']})" for r in runs)
        lines.append(f"Engine speed in Node {runs[0]['node']} with the int8 file: {speed}.")
    parity = release / "parity_report.json"
    if parity.exists():
        report = json.loads(parity.read_text(encoding="utf-8"))
        worst = max(r["maxAbsLogitDiff"] for r in report["engine"].values())
        constrained = sorted({r.get("constrainedIdentical", "-") for r in report["engine"].values()})
        lines.append(f"Engine parity against PyTorch ({'ok' if report['ok'] else 'FAILED'}): largest logit difference "
                     f"{worst:.1e} over {len(report['engine'])} format x kernel combinations; constrained greedy "
                     f"answers identical: {', '.join(constrained)}.")
    answers = release / "answers_parity.json"
    if answers.exists():
        a = json.loads(answers.read_text(encoding="utf-8"))
        lines.append(f"End to end: of {a['questions']} held-out {a['split']} questions asked through the browser "
                     f"session in Node and through Python with the {a['format']} file, {a['identical_answers']} got "
                     f"the same answer and {a['identical_retrieved_facts']} the same retrieved facts.")
    if not info.get("final_split_read"):
        lines.append("The final slice has not been read for this release.")
    return "\n\n".join(_paragraphs(lines))


def _paragraphs(lines: list[str]) -> list[str]:
    """Group the table rows into one block; every other line is its own paragraph."""
    out, table = [], []
    for line in lines:
        if line.startswith("|"):
            table.append(line)
            continue
        if table:
            out.append("\n".join(table))
            table = []
        if line:
            out.append(line)
    if table:
        out.append("\n".join(table))
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("releases", nargs="+", help="release directories written by scripts/release.sh")
    ap.add_argument("--readme", default=str(ROOT / "README.md"))
    ap.add_argument("--print", action="store_true", help="print the block instead of rewriting the README")
    args = ap.parse_args()
    block = "\n\n".join(release_block(Path(r)) for r in args.releases)
    if args.print:
        print(block)
        return
    readme = Path(args.readme)
    text = readme.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{readme} has no RELEASE-TABLE markers")
    start, end = text.index(BEGIN) + len(BEGIN), text.index(END)
    readme.write_text(text[:start] + "\n" + block + "\n" + text[end:], encoding="utf-8")
    print(f"updated {readme} from {', '.join(args.releases)}")


if __name__ == "__main__":
    main()
